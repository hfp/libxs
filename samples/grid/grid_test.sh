# Every sample task with CP2K's DGEMM backend twice: LIBXSMM's kernels (through
# LIBXS) dump the task list with their results, and a replay with BLAS compares
# against them. The sample's own reference does not decide: it measures the
# DGEMM backend, which deviates on some synthetic samples.
# Usage: grid_test.sh <grid_miniapp.x> <sample_tasks directory> <work directory>
set -eo pipefail

if [ ! -x "$1" ] || [ ! -d "$2" ] || [ ! "$3" ]; then
  >&2 echo "Usage: $0 <grid_miniapp.x> <sample_tasks directory> <work directory>"
  exit 1
fi
MINIAPP=$(cd "$(dirname "$1")" && pwd -P)/$(basename "$1")
TASKDIR=$(cd "$2" && pwd -P)
WORKDIR=$(mkdir -p "$3" && cd "$3" && pwd -P)

# a kernel from the first call of a shape, since a replay calls each shape a few times
export LIBXS_GEMM_JIT_WARMUP=0

FAILED=0
NJIT=0
for TASK in "${TASKDIR}"/*.task; do
  # the DGEMM backend overflows on this synthetic sample whatever the GEMM
  if [ "general_skewed.task" = "$(basename "${TASK}")" ]; then continue; fi
  for MODE in collocate integrate; do
    if [ "integrate" = "${MODE}" ]; then ARGS=(--integrate); else ARGS=(); fi
    rm -rf "${WORKDIR}" && mkdir -p "${WORKDIR}" && cd "${WORKDIR}"
    # exit code 2: a result deviates from the sample's own reference
    RESULT=0
    LIBXSMM_VERBOSE=2 LIBXS_GEMM_BACKEND=2 "${MINIAPP}" --backend dgemm \
      --batch 1 "${ARGS[@]}" --dump 1 1 "${TASK}" >run_a.log 2>&1 || RESULT=$?
    # kernels generated by LIBXSMM (JIT column of its statistics)
    JIT=$(awk '/\/DP/ { table = 1; next } table && 5 == NF { n += $3 } END { print n + 0 }' run_a.log)
    NJIT=$((NJIT + JIT))
    if [ 0 != "${RESULT}" ] && [ 2 != "${RESULT}" ]; then
      echo "ERROR: ${TASK} (${MODE}) failed with exit code ${RESULT}"; cat run_a.log; FAILED=1
    fi
    NLIST=0
    for LIST in *.tasklist; do
      if [ ! -e "${LIST}" ]; then continue; fi
      NLIST=$((NLIST + 1))
      if LIBXS_GEMM_BACKEND=3 "${MINIAPP}" --backend dgemm 1 "${LIST}" >run_b.log 2>&1; then
        echo "$(basename "${TASK}") ${MODE}: $(grep -o 'Max rel diff: [^ ]*' run_b.log) (${JIT} kernels)"
      else
        echo "ERROR: ${TASK} (${MODE}) differs from BLAS"; cat run_b.log; FAILED=1
      fi
    done
    if [ 0 = "${NLIST}" ]; then
      echo "ERROR: ${TASK} (${MODE}) dumped no task list"; FAILED=1
    fi
  done
done
if [ 0 = "${NJIT}" ]; then
  echo "ERROR: LIBXSMM generated no kernel, i.e., LIBXS handed every GEMM to BLAS"; FAILED=1
fi
exit ${FAILED}
